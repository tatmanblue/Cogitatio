using Azure;
using Azure.Storage.Blobs;
using Azure.Storage.Blobs.Models;
using Cogitatio.Interfaces;

namespace Cogitatio.Logic;

/// <summary>
/// Used when no image store is configured (Admin > Settings > Images). Uploads are disabled.
/// </summary>
public class DisabledImageStore : IImageStore
{
    public bool IsConfigured => false;

    public Task SaveAsync(string storagePath, Stream data, string contentType) =>
        throw new InvalidOperationException("No image store is configured. Set one in Admin > Settings > Images.");

    public Task<Stream?> OpenReadAsync(string storagePath) => Task.FromResult<Stream?>(null);

    public Task DeleteAsync(string storagePath) => Task.CompletedTask;
}

/// <summary>
/// Stores images in a folder on the server. Intended for development: on Azure App Service a
/// zip deploy replaces the site folder, so use Azure Blob storage in production.
/// </summary>
public class LocalImageStore : IImageStore
{
    private readonly ILogger<IImageStore> logger;
    private readonly string rootPath;

    public LocalImageStore(ILogger<IImageStore> logger, string rootPath)
    {
        this.logger = logger;
        this.rootPath = Path.GetFullPath(rootPath);
    }

    public bool IsConfigured => true;

    public async Task SaveAsync(string storagePath, Stream data, string contentType)
    {
        string fullPath = ResolvePath(storagePath);
        Directory.CreateDirectory(Path.GetDirectoryName(fullPath)!);
        await using FileStream file = new FileStream(fullPath, FileMode.CreateNew, FileAccess.Write);
        await data.CopyToAsync(file);
        logger.LogDebug("Image written to {Path}", fullPath);
    }

    public Task<Stream?> OpenReadAsync(string storagePath)
    {
        string fullPath = ResolvePath(storagePath);
        if (!File.Exists(fullPath))
            return Task.FromResult<Stream?>(null);

        Stream stream = new FileStream(fullPath, FileMode.Open, FileAccess.Read, FileShare.Read, 81920, useAsync: true);
        return Task.FromResult<Stream?>(stream);
    }

    public Task DeleteAsync(string storagePath)
    {
        string fullPath = ResolvePath(storagePath);
        if (File.Exists(fullPath))
            File.Delete(fullPath);
        return Task.CompletedTask;
    }

    private string ResolvePath(string storagePath)
    {
        // Storage paths are generated by ImageService, but guard against traversal anyway.
        string fullPath = Path.GetFullPath(Path.Combine(rootPath, storagePath));
        if (!fullPath.StartsWith(rootPath + Path.DirectorySeparatorChar, StringComparison.OrdinalIgnoreCase))
            throw new InvalidOperationException($"Invalid image storage path: {storagePath}");
        return fullPath;
    }
}

/// <summary>
/// Stores images in a private Azure Blob container. Images are served through /img/{id},
/// so the container never needs public access.
/// </summary>
public class AzureBlobImageStore : IImageStore
{
    private readonly ILogger<IImageStore> logger;
    private readonly BlobContainerClient container;
    private bool containerChecked = false;

    public AzureBlobImageStore(ILogger<IImageStore> logger, string connectionString, string containerName)
    {
        this.logger = logger;
        container = new BlobContainerClient(connectionString, containerName);
    }

    public bool IsConfigured => true;

    public async Task SaveAsync(string storagePath, Stream data, string contentType)
    {
        if (!containerChecked)
        {
            await container.CreateIfNotExistsAsync(PublicAccessType.None);
            containerChecked = true;
        }

        BlobClient blob = container.GetBlobClient(storagePath);
        BlobUploadOptions options = new BlobUploadOptions
        {
            HttpHeaders = new BlobHttpHeaders { ContentType = contentType },
            // never overwrite an existing image; paths include a new GUID so this shouldn't happen
            Conditions = new BlobRequestConditions { IfNoneMatch = ETag.All }
        };
        await blob.UploadAsync(data, options);
        logger.LogDebug("Image uploaded to blob {Path}", storagePath);
    }

    public async Task<Stream?> OpenReadAsync(string storagePath)
    {
        try
        {
            BlobClient blob = container.GetBlobClient(storagePath);
            Response<BlobDownloadStreamingResult> response = await blob.DownloadStreamingAsync();
            return response.Value.Content;
        }
        catch (RequestFailedException ex) when (ex.Status == 404)
        {
            logger.LogWarning("Image blob not found: {Path}", storagePath);
            return null;
        }
    }

    public async Task DeleteAsync(string storagePath)
    {
        await container.GetBlobClient(storagePath).DeleteIfExistsAsync();
    }
}
